pub async fn register_capabilities(registry: &CapabilityRegistry) -> Result<()> {
    for (id, name, description, risk) in [
        ("selfmade.observe", "SelfMade Observe", "Inspect JAMES runtime and development state", RiskLevel::Low),
        ("selfmade.propose", "SelfMade Propose", "Create a bounded source change proposal", RiskLevel::Medium),
        ("selfmade.verify", "SelfMade Verify", "Run deterministic verification in isolated workspace", RiskLevel::Medium),
        ("selfmade.rollback", "SelfMade Rollback", "Discard an unpromoted self-development workspace change", RiskLevel::High),
    ] {
        registry.register(CapabilityDefinition {
            id: id.into(),
            name: name.into(),
            category: CapabilityCategory::Custom("selfmade".into()),
            version: "1.0.0".into(),
            provider: "james.selfmade".into(),
            description: description.into(),
            risk_level: risk,
            required_permissions: vec![],
            dependencies: vec![],
            input_schema: None,
            output_schema: None,
            execution_target: ExecutionTarget::Local,
            tags: vec!["selfmade".into(), "development".into()],
            deprecated: false,
            experimental: true,
        }, "james.selfmade".into()).await?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use james_events::EventBus;

    #[tokio::test]
    async fn mission_starts_in_observe_state() {
        let bus = Arc::new(EventBus::new(32));
        let registry = Arc::new(CapabilityRegistry::new());
        let module = SelfMadeModule::new(".", bus, registry);
        let mission = module.new_mission("improve runtime");
        assert_eq!(mission.status, MissionStatus::Observing);
        assert!(!mission.id.is_empty());
    }

    #[tokio::test]
    async fn self_observation_contains_identity_and_capabilities() {
        let bus = Arc::new(EventBus::new(32));
        let registry = Arc::new(CapabilityRegistry::new());
        registry.register(CapabilityDefinition {
            id: "test.capability".into(),
            name: "Test".into(),
            category: CapabilityCategory::Custom("test".into()),
            version: "1.0.0".into(),
            provider: "test".into(),
            description: "test".into(),
            risk_level: RiskLevel::Low,
            required_permissions: vec![],
            dependencies: vec![],
            input_schema: None,
            output_schema: None,
            execution_target: ExecutionTarget::Local,
            tags: vec![],
            deprecated: false,
            experimental: false,
        }, "test").await.unwrap();
        let module = SelfMadeModule::new(std::env::temp_dir().join(format!("james-self-{}", Uuid::now_v7())), bus, registry);
        module.start().await.unwrap();
        let state = module.observe_self().await.unwrap();
        assert_eq!(state["identity"]["name"], "JAMES");
        assert_eq!(state["runtime"]["capability_count"], 1);
        let _ = tokio::fs::remove_dir_all(module.root.clone()).await;
    }

    #[tokio::test]
    async fn manifest_is_selfmade() {
        assert_eq!(manifest().id, "james.selfmade");
    }
}
